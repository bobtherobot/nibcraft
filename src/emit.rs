//! Writing a parsed glyph as Rust: a `const` of the [`runtime/glyph.rs`] types for `cursors.rs`.

use crate::geom::Pt;
use crate::parse::{Glyph, Part};
use std::fmt::Write as _;

/// `PenAdd.svg` (or `pen-add.svg`) → `PEN_ADD`: a word starts at each capital after a lowercase
/// letter or digit.
pub fn const_name(file_stem: &str) -> String {
    let mut name = String::new();
    let mut after_word = false;
    for c in file_stem.chars() {
        if c.is_ascii_uppercase() && after_word {
            name.push('_');
        }
        after_word = c.is_ascii_lowercase() || c.is_ascii_digit();
        name.push(if c.is_ascii_alphanumeric() { c.to_ascii_uppercase() } else { '_' });
    }
    if name.chars().next().is_none_or(|c| c.is_ascii_digit()) {
        name.insert(0, '_');
    }
    name
}

/// A short, stable fingerprint of the SVG bytes (FNV-1a), so a stale paste is easy to spot.
pub fn fingerprint(bytes: &[u8]) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for &b in bytes {
        h ^= u64::from(b);
        h = h.wrapping_mul(0x0100_0000_01b3);
    }
    format!("{:08x}", h >> 32)
}

/// A value as the whole hundredths it's emitted with.
fn hundredths(v: f32) -> i32 {
    (v * 100.0).round() as i32
}

/// A fingerprint of a glyph's data as emitted, so VectorCraft's record test can tell a generated
/// `const` that was edited by hand: [`fingerprint`] (FNV-1a) over, part by part, a kind byte (0 fill,
/// 1 stroke), a white byte, a closed byte (1 for fills), the width (0 for fills) and the point count,
/// then each point's x and y, then each triangle's indices. Numbers are little-endian: widths and
/// coordinates as i32 hundredths, counts as u32, indices as u16. VectorCraft computes the same sum.
pub fn data_fingerprint(g: &Glyph) -> String {
    let mut bytes = Vec::new();
    for part in &g.parts {
        let (kind, pts, tris, closed, width, white): (u8, &[Pt], &[[u16; 3]], bool, f32, bool) = match part {
            Part::Fill { points, tris, white } => (0, points, tris, true, 0.0, *white),
            Part::Stroke { points, closed, width, white } => (1, points, &[], *closed, *width, *white),
        };
        bytes.extend([kind, u8::from(white), u8::from(closed)]);
        bytes.extend(hundredths(width).to_le_bytes());
        bytes.extend((pts.len() as u32).to_le_bytes());
        for &(x, y) in pts {
            bytes.extend(hundredths(x).to_le_bytes());
            bytes.extend(hundredths(y).to_le_bytes());
        }
        for t in tris {
            for i in t {
                bytes.extend(i.to_le_bytes());
            }
        }
    }
    fingerprint(&bytes)
}

fn num(v: f32) -> String {
    let r = (v * 100.0).round() / 100.0;
    let r = if r == 0.0 { 0.0 } else { r }; // no "-0.0"
    let s = format!("{r:.2}");
    let s = s.trim_end_matches('0');
    if s.ends_with('.') { format!("{s}0") } else { s.to_string() }
}

fn points(pts: &[Pt]) -> String {
    let items: Vec<String> = pts.iter().map(|&(x, y)| format!("({}, {})", num(x), num(y))).collect();
    format!("&[{}]", items.join(", "))
}

/// `g` as a `const` named `name`. VectorCraft names a cursor by its `id` (the file stem, its
/// `Cursor` value), never by file, so nothing here says SVG.
pub fn glyph(name: &str, id: &str, svg_bytes: &[u8], g: &Glyph) -> String {
    let fp = fingerprint(svg_bytes);
    let mut out = String::new();
    let _ = writeln!(out, "/// Generated by nibcraft from its `{id}` cursor ({fp}). Don't edit by hand: redraw it in");
    let _ = writeln!(out, "/// nibcraft and regenerate. Points relative to the hotspot, at ({}, {}) in the drawing.", num(g.hotspot.0), num(g.hotspot.1));
    let _ = writeln!(out, "#[rustfmt::skip]");
    let _ = writeln!(out, "#[allow(clippy::approx_constant, reason = \"generated coordinates, such as 6.28\")]");
    let _ = writeln!(out, "const {name}: Glyph = Glyph {{");
    let _ = writeln!(out, "    id: {id:?}, fp: \"{fp}\", data_fp: \"{}\",", data_fingerprint(g));
    let _ = writeln!(out, "    parts: &[");
    for part in &g.parts {
        match part {
            Part::Fill { points: pts, tris, white } => {
                let t: Vec<String> = tris.iter().map(|t| format!("[{}, {}, {}]", t[0], t[1], t[2])).collect();
                let _ = writeln!(out, "        GlyphPart::Fill {{ points: {}, tris: &[{}], white: {white} }},", points(pts), t.join(", "));
            }
            Part::Stroke { points: pts, closed, width, white } => {
                let _ = writeln!(out, "        GlyphPart::Stroke {{ points: {}, closed: {closed}, width: {}, white: {white} }},", points(pts), num(*width));
            }
        }
    }
    let _ = writeln!(out, "    ],");
    let _ = writeln!(out, "}};");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_and_numbers() {
        assert_eq!(const_name("pen-nib"), "PEN_NIB");
        assert_eq!(const_name("2x"), "_2X");
        assert_eq!(const_name("PenAdd"), "PEN_ADD");
        assert_eq!(const_name("ResizeNeSw"), "RESIZE_NE_SW");
        assert_eq!(const_name("ResizeH"), "RESIZE_H");
        assert_eq!(const_name("RotateToward1"), "ROTATE_TOWARD1");
        assert_eq!(const_name("Pen2Add"), "PEN2_ADD");
        assert_eq!(num(1.0), "1.0");
        assert_eq!(num(-0.001), "0.0");
        assert_eq!(num(1.23456), "1.23");
        assert_eq!(num(1.2), "1.2");
    }

    #[test]
    fn glyph_names_its_id_and_fingerprint() {
        let g = crate::parse::read(include_bytes!("../testdata/round-trip-checker.svg")).unwrap();
        let out = glyph("NIB", "Nib\"x", b"abc", &g);
        let want = format!("    id: \"Nib\\\"x\", fp: \"{}\", data_fp: \"{}\",\n    parts: &[\n", fingerprint(b"abc"), data_fingerprint(&g));
        assert!(out.contains(&want), "{out}");
        assert!(!out.to_lowercase().contains("svg"), "VectorCraft names cursors by id, not by file: {out}");
    }

    #[test]
    fn glyph_carries_a_fingerprint_of_its_emitted_data() {
        let mut g = crate::parse::read(include_bytes!("../testdata/round-trip-checker.svg")).unwrap();
        let out = glyph("NIB", "Nib", b"abc", &g);
        let fp = data_fingerprint(&g);
        assert!(out.contains(&format!("data_fp: \"{fp}\",")), "{out}");
        let mut nudge = |d: f32| {
            let (Part::Fill { points, .. } | Part::Stroke { points, .. }) = &mut g.parts[0];
            points[0].0 += d;
            data_fingerprint(&g)
        };
        assert_eq!(nudge(0.001), fp, "below the emitted precision");
        assert_ne!(nudge(0.01), fp, "a visible change");
    }

    #[test]
    fn coordinates_that_look_like_constants_dont_trip_clippy() {
        let g = crate::parse::read(include_bytes!("../testdata/round-trip-checker.svg")).unwrap();
        let out = glyph("NIB", "Nib", b"abc", &g);
        assert!(out.contains("#[allow(clippy::approx_constant, reason = \"generated coordinates, such as 6.28\")]\nconst NIB"), "{out}");
    }
}
