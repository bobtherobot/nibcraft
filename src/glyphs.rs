//! `nibcraft glyphs PROJECT ID…`: the app's sync asks for its cursors by id and gets, as JSON,
//! the generated `const` of each one that's drawn, the ones that aren't, the drawings that don't
//! convert, and the designer's notes. The app decides which ids to ask for.

use crate::emit::{self, const_name, fingerprint};
use crate::parse;
use crate::project::Project;
use std::path::Path;
use std::process::Command;

/// `s` as a JSON string literal.
fn string(s: &str) -> String {
    let mut out = String::from('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if u32::from(c) < 0x20 => out.push_str(&format!("\\u{:04x}", u32::from(c))),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// An id is a cursor's name: letters and digits only, so it can't reach outside `svg/`.
fn is_id(id: &str) -> bool {
    !id.is_empty() && id.chars().all(|c| c.is_ascii_alphanumeric())
}

/// The JSON answer for `ids` in project `p`. `source` names the nibcraft version they come from.
pub fn answer(p: &Project, ids: &[String], source: &str) -> Result<String, String> {
    let mut glyphs = vec![];
    let mut missing = vec![];
    let mut errors = vec![];
    for id in ids {
        if !is_id(id) {
            return Err(format!("{id:?} isn't a cursor id"));
        }
        let path = p.svg_dir().join(format!("{id}.svg"));
        let bytes = match std::fs::read(&path) {
            Ok(b) => b,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                missing.push(string(id));
                continue;
            }
            Err(e) => return Err(format!("{}: {e}", path.display())),
        };
        match parse::read(&bytes) {
            Ok(g) => glyphs.push(format!(
                r#"{{"id": {}, "const": {}, "fp": {}, "code": {}}}"#,
                string(id),
                string(&const_name(id)),
                string(&fingerprint(&bytes)),
                string(&emit::glyph(&const_name(id), id, &bytes, &g))
            )),
            Err(e) => errors.push(format!(r#"{{"id": {}, "error": {}}}"#, string(id), string(&e))),
        }
    }
    let pulled = crate::check::pulled(p);
    let app = pulled.manifest.ok().and_then(|m| m.app).unwrap_or_else(|| p.name.clone());
    let notes = crate::notes::written(&std::fs::read_to_string(p.notes()).unwrap_or_default(), &app);
    let stamp = pulled.stamp.unwrap_or_default();
    Ok(format!(
        "{{\n  \"source\": {},\n  \"pulled\": {},\n  \"notes\": {},\n  \"glyphs\": [{}],\n  \"missing\": [{}],\n  \"errors\": [{}]\n}}\n",
        string(source),
        string(&stamp),
        string(&notes),
        glyphs.join(",\n    "),
        missing.join(", "),
        errors.join(",\n    ")
    ))
}

/// nibcraft's commit, with `-dirty` when the project folder has changes not committed yet.
pub fn source(root: &Path, p: &Project) -> String {
    let git = |args: &[&str]| {
        let out = Command::new("git").arg("-C").arg(root).args(args).output().ok()?;
        out.status.success().then(|| String::from_utf8_lossy(&out.stdout).trim().to_string())
    };
    let Some(hash) = git(&["rev-parse", "--short", "HEAD"]) else { return "unknown".into() };
    let dirty = git(&["status", "--porcelain", "--", &p.dir.to_string_lossy()]).is_some_and(|s| !s.is_empty());
    if dirty { format!("{hash}-dirty") } else { hash }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::project::tests::root;

    const NIB: &[u8] = include_bytes!("../testdata/round-trip-checker.svg");

    #[test]
    fn answers_glyphs_missing_ids_errors_and_notes() {
        let r = root("glyphs");
        let p = Project::at(&r, "v");
        std::fs::create_dir_all(p.svg_dir()).unwrap();
        std::fs::write(p.svg_dir().join("Pen.svg"), NIB).unwrap();
        std::fs::write(p.svg_dir().join("Knife.svg"), "<svg/>").unwrap();
        std::fs::write(p.svg_dir().join("Extra.svg"), NIB).unwrap();
        std::fs::write(p.notes(), "Make \"Pen\" bolder?\n").unwrap();
        let json = answer(&p, &["Pen".into(), "Lasso".into(), "Knife".into()], "abc1234").unwrap();
        assert!(json.contains(r#""source": "abc1234""#), "{json}");
        assert!(json.contains(&format!(r#""id": "Pen", "const": "PEN", "fp": "{}", "code": "/// Generated by nibcraft from its `Pen` cursor"#, fingerprint(NIB))), "{json}");
        assert!(json.contains(r#""missing": ["Lasso"]"#), "{json}");
        assert!(json.contains(r#""errors": [{"id": "Knife", "error": "#), "{json}");
        assert!(json.contains(r#""notes": "Make \"Pen\" bolder?""#), "{json}");
        assert!(!json.contains("Extra"), "only the ids asked for: {json}");
    }

    #[test]
    fn ids_cant_be_paths() {
        let r = root("glyphs-bad");
        let p = Project::at(&r, "v");
        assert!(answer(&p, &["../secret".into()], "x").unwrap_err().contains("isn't a cursor id"));
        assert!(answer(&p, &[String::new()], "x").is_err());
    }

    #[test]
    fn json_strings_are_escaped() {
        assert_eq!(string("a\"b\\c\nd\u{1}é"), r#""a\"b\\c\nd\u0001é""#);
    }
}
